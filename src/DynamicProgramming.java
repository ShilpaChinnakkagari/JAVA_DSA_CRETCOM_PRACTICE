/*
DYNAMIC PROGRAMMING :
-----------------------
=> DP is an optimization technique, used to solve problems by breaking them into smaller overlapping problems
  solving each problem only once, and storing the result for reuse.

 => A problem can be solved using DP if it has,
    1. Overlapping sub problems
    2. Optimal Structure

    The two Approaches are :
        1. Top-Down Approach ---> Uses Recursion, stores the result in an array and avoids recomputation.
                TC : O(N) or O(N^2)
        2. Bottom - Up Approach ---> Uses Iteration, builds a solution from smallest sub-problem
 */